const {test}=require('node:test');const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {initializeLocalHome}=require('@openhilo/server/local-initialize');
const {createLocalDeployment}=require('@openhilo/server/local-deployment');
const example=path.resolve(path.dirname(require.resolve('@openhilo/server')),'../examples/routed-local');
const {createDeploymentOptions}=require(path.join(example,'composition.cjs'));
const {readSelection}=require(path.join(example,'config.cjs'));
const wait=async read=>{for(let i=0;i<800;i++){const x=await read();if(x)return x;await new Promise(r=>setTimeout(r,10));}throw Error('Codex fixture operation timed out')};
test('Routed preset accepts compatible alternate version metadata, repairs, publishes and executes AI plus real Bash without other providers', {timeout:30000},async t=>{
 const root=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'codex-deployment-'))),home=path.join(root,'home');
 const cfg=JSON.parse(fs.readFileSync(path.join(example,'config.example.json'),'utf8'));
 cfg.ai.execution.routes.default.levels.medium.cli_path=[path.resolve(__dirname,'fixtures/protocol-peer.cjs'),path.resolve(__dirname,'../../../tests/fixtures/protocol-peer.cjs')].find(fs.existsSync);
 // Independent consumers copy the fixture to the same relative location.
 cfg.ai.execution.routes.default.levels.medium.timeout_ms=5000;
 delete cfg.ai.execution.routes.coding;
 initializeLocalHome({home,configuration:cfg});let host;
 t.after(async()=>{await host?.close();fs.rmSync(root,{recursive:true,force:true});});
 host=await createLocalDeployment({home,...createDeploymentOptions({home})});
 const request=async(method,url,payload,status=200)=>{const r=await host.app.inject({method,url,payload});assert.equal(r.statusCode,status,r.body);return r.body?r.json():undefined;};
 const publicConfig=await request('GET','/api/config');
 assert.equal(publicConfig.ai_execution.adapter,'routed');
 assert.deepEqual(publicConfig.configuration_status,{activation:'restart',restart_required:false,editable:true});
 const rejected=await request('PUT','/api/config',{ai_execution:{adapter:'sdk'},configuration_revision:publicConfig.configuration_revision},400);
 assert.match(rejected.error,/requires routed/);
 assert.deepEqual(await request('GET','/api/config'),publicConfig);
 const creation={requestId:require('node:crypto').randomUUID(),naturalLanguage:'trigger compiler repair; Create a tiny report'};
 const generated=await request('POST','/api/translate/start',creation);
 assert.equal(generated.sessionId,creation.requestId);
 assert.equal(generated.step.phase,'cc_running',JSON.stringify(generated));
 const review=await wait(async()=>{const step=await request('GET',`/api/translate/${generated.sessionId}`);return step.phase==='cc_running'||step.phase==='auto_fixing'?null:step;});
 assert.equal(review.phase,'confirm_merge',JSON.stringify(review));
 assert.equal((await request('POST','/api/translate/start',creation)).sessionId,generated.sessionId);
 await request('POST','/api/translate/start',{...creation,naturalLanguage:'conflicting request'},409);
 await request('POST','/api/translate/start',{...creation,requestId:'../outside'},400);
 assert.equal((await request('GET','/api/translate?limit=100')).total,1);
 await host.close();host=await createLocalDeployment({home,...createDeploymentOptions({home})});
 assert.equal((await request('POST','/api/translate/start',creation)).sessionId,generated.sessionId);
 const refreshed=await request('POST',`/api/translate/${generated.sessionId}/respond`,{type:'merge_approve',reviewId:review.reviewId});
 assert.equal(refreshed.phase,'confirm_merge');assert.notEqual(refreshed.reviewId,review.reviewId);
 assert.equal(fs.existsSync(path.join(home,'intents/codex/report/report.itt.impl.json')),false);
 assert.equal((await request('POST',`/api/translate/${generated.sessionId}/respond`,{type:'merge_approve',reviewId:refreshed.reviewId})).phase,'done');
 const workdir=path.join(home,'workspaces','run');
 const {runId}=await request('POST','/api/runs',{ittPath:'codex/report/report.itt.impl.json',workdir,inputs:{}},201);
 await wait(()=>!host.workers.isActive(runId));
 assert.equal((await request('GET',`/api/runs/${runId}`)).status,'completed');
 assert.equal(fs.readFileSync(path.join(workdir,'report.txt'),'utf8'),'ok');
 const first=readSelection(home);cfg.ai.execution.routes.default.levels.medium.model='changed';fs.writeFileSync(path.join(home,'config.json'),JSON.stringify(cfg));
 assert.notEqual(readSelection(home).identity,first.identity);
});
